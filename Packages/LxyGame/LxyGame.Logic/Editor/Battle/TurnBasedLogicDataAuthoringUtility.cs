        private const string GeneratedRoot =
            "Packages/LxyGame/LxyGame.Logic/Runtime/Battle/TurnBased/Generated";

        public static void GenerateAll()
        {
            List<TurnBasedSkillLogicAsset> assets =
                TurnBasedAssetEditorUtility.FindAssets<TurnBasedSkillLogicAsset>();
            for (int index = 0; index < assets.Count; index++)
            {
                if (!assets[index].TryValidate(out string error))
                {
                    throw new InvalidOperationException(
                        $"技能逻辑 {assets[index].LogicId} 校验失败：{error}");
                }
            }

            for (int index = 0; index < assets.Count; index++)
            {
                GenerateCode(assets[index]);
            }
            AssetDatabase.Refresh(ImportAssetOptions.ForceUpdate);
            Debug.Log($"[TurnBasedLogicEditor] 已生成 {assets.Count} 份技能逻辑 C#。");
        }

        public static void ShowTemplateMenu(
